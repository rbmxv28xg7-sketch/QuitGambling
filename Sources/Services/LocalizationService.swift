    var currentLanguage: String = "de" {
        didSet {
            UserDefaults.standard.set(currentLanguage, forKey: "app_language_code")
        }
    }

    private init() {
        if let saved = UserDefaults.standard.string(forKey: "app_language_code"), !saved.isEmpty {
            self.currentLanguage = saved
        } else {
            let deviceLang = Locale.current.language.languageCode?.identifier ?? "en"
            self.currentLanguage = ["de", "es", "fr", "en"].contains(deviceLang) ? deviceLang : "en"
        }
    }

    func tr(_ key: String) -> String {
        let lang = currentLanguage
        if let dict = translations[lang], let val = dict[key] {
            return val
        }
        if let enDict = translations["en"], let val = enDict[key] {
            return val
        }
        return key
    }

    func tr(_ key: String, _ args: [CVarArg]) -> String {
        let format = tr(key)
        let locale = Locale(identifier: currentLanguage)
        return String(format: format, locale: locale, arguments: args)
    }

